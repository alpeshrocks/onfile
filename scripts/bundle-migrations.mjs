// Bundles the SQL emitted by drizzle-kit into a TypeScript module.
// The app applies migrations from code at first use, so it needs no filesystem
// access at runtime (serverless friendly) and local and hosted databases cannot drift.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "drizzle");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const migrations = files.map((file) => ({
  id: file.replace(/\.sql$/, ""),
  statements: readFileSync(join(dir, file), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));

const out = `// GENERATED by scripts/bundle-migrations.mjs. Do not edit by hand.
// Source of truth: src/server/db/schema.ts (run \`npm run db:generate\`).
export const migrations: { id: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(join(root, "src/server/db/migrations.generated.ts"), out);
console.log(`Bundled ${migrations.length} migration(s).`);
